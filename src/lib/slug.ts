/**
 * Transforme un texte en slug URL : minuscules, sans accents,
 * tirets à la place des espaces/ponctuation.
 */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
